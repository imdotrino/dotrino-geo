/**
 * Copia al servidor lo que comparte con el cliente.
 *
 * El servidor es CommonJS y su imagen Docker se construye con contexto `./server`, así que
 * no puede importar `../src`. En vez de tener `canonicalStringify` y `normalizeTags` escritos
 * dos veces (y la firma dependiendo de que las dos den lo mismo byte a byte), la fuente es
 * `src/` y este script genera `server/vendor/shared.js`. `test/vendor-up-to-date.test.js`
 * FALLA si alguien tocó `src/` y no lo corrió.
 *
 *   node vendor.mjs
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))

export const SOURCES = ['src/canonical.js', 'src/tags.js']
export const TARGET = 'server/vendor/shared.js'

/** El contenido que debe tener TARGET, generado desde SOURCES. */
export function render () {
  const names = []
  const bodies = SOURCES.map((rel) => {
    const src = readFileSync(join(here, rel), 'utf8')
    if (/^\s*import\s/m.test(src)) throw new Error(`vendor: ${rel} has imports; only self-contained files can be vendored`)
    const out = src.replace(/^export function (\w+)/gm, (_, name) => { names.push(name); return `function ${name}` })
    if (/^export\s/m.test(out)) throw new Error(`vendor: ${rel} has an export other than "export function"`)
    return `// ── ${rel} ──\n${out.trimEnd()}\n`
  })
  return [
    '// GENERATED by vendor.mjs from ' + SOURCES.join(', ') + '. Do not edit: edit src/ and run `node vendor.mjs`.',
    "'use strict'",
    '',
    bodies.join('\n'),
    `module.exports = { ${names.join(', ')} }`,
    ''
  ].join('\n')
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  mkdirSync(dirname(join(here, TARGET)), { recursive: true })
  writeFileSync(join(here, TARGET), render())
  console.log(`vendor: ${SOURCES.join(', ')} → ${TARGET}`)
}
